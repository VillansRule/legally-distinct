/* =====================================================
   LOAD ROUND
===================================================== */

function loadRound() {

    roundSubmitted = false;

    const config =
        getDifficultyConfig(level);

    const difficulty =
        config.difficulty;

    let nextQuestionIndex = Math.floor(
        Math.random() *
        questions.length
    );


    if (
        usedQuestionIndexes.length >= questions.length
    ) {
        usedQuestionIndexes = [];
    }


    while (
        usedQuestionIndexes.includes(
            nextQuestionIndex
        )
    ) {
        nextQuestionIndex = Math.floor(
            Math.random() *
            questions.length
        );
    }


    usedQuestionIndexes.push(
        nextQuestionIndex
    );

    currentQuestion =
        questions[nextQuestionIndex];

    currentModifier =
        config.modifierText;

    const fullPrompt =
        `${currentQuestion.prompt} ${difficulty.promptBonus} ${currentModifier}`;

    levelNumber.textContent =
        level + 1;


    category.textContent =
        currentQuestion.category;


    prompt.textContent =
        fullPrompt;

    updateProgressStatus();

    updateChallengeLog(config);


    reference.textContent =
        currentQuestion.reference;


    const answerIndex =
        Math.min(
            level,
            currentQuestion.phairAnswers.length - 1
        );

    phairAnswer.textContent =
        currentQuestion.phairAnswers[answerIndex];


    playerAnswer.value =
        "";


    progressFill.style.width =
        `${Math.min(
            100,
            ((level + 1) / 10) * 100
        )}%`;


    gameScreen.classList.remove(
        "hidden"
    );

    resultsScreen.classList.add(
        "hidden"
    );

    finalScreen.classList.add(
        "hidden"
    );


    startTimer(
        config.timeLimit
    );


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });


    setTimeout(
        () => {
            playerAnswer.focus();
        },
        200
    );

}


