/* =====================================================
   LOCAL JUDGE
===================================================== */

function analyzeAnswer(
    answer
) {

    const text =
        (answer || "")
            .trim();


    if (
        text.length === 0
    ) {
        return {
            score: 0,
            details: {
                wordCount: 0,
                uniqueRatio: 0,
                hasSpecificConcept: false,
                hasRole: false,
                hasMotivation: false,
                hasDistinctiveHook: false,
                hasWeakness: false,
                hasVisualIdentity: false,
                hasStructure: false
            }
        };
    }


    const words =
        text
            .split(/\s+/)
            .filter(Boolean);


    const normalizedWords =
        words.map(
            word =>
                word
                    .toLowerCase()
                    .replace(/[^a-z0-9]/g, "")
        );


    const uniqueRatio =
        normalizedWords.length === 0
            ? 0
            : new Set(
                normalizedWords
            ).size /
              normalizedWords.length;


    const hasSpecificConcept =
        /(power|ability|device|armor|suit|team|city|academy|agency|school|program|mutation|engineer|pilot|rescue|drone|network|portal|energy|system|shield|exoskeleton|laboratory|signal|guild|circuit|prototype)/i
            .test(text);


    const hasRole =
        /(hero|villain|guardian|pilot|engineer|scientist|detective|leader|agent|ranger|student|architect|rescue|officer|warrior|mage|scholar|sentinel|warden)/i
            .test(text);


    const hasMotivation =
        /(protect|save|defend|prevent|stop|investigate|serve|guide|guard|rescue|rebuild|watch|lead|control|reform|expose|help|serve)/i
            .test(text);


    const hasDistinctiveHook =
        /(instead of|rather than|without|not|uses|relies on|built from|designed for|transforms|mutation|modular|network|academy|agency|company|system|prototype|inspired by|specializes in)/i
            .test(text);


    const hasWeakness =
        /(weakness|flaw|limit|cost|drawback|requires|exhausting|dangerous|vulnerable|cannot|must|only works|if)/i
            .test(text);


    const hasVisualIdentity =
        /(costume|suit|armor|mask|cloak|jacket|plates|gloves|colors|uniform|appearance|design)/i
            .test(text);


    const hasStructure =
        /(team|group|organization|academy|coalition|alliance|program|network|guild|pact|initiative)/i
            .test(text);


    let score = 1;


    // DISTINCTIVENESS IS CRITICAL
    if (
        hasDistinctiveHook
    ) {
        score += 3;
    }
    else {
        score -= 1;
    }


    // LENGTH: Less generous, but still reward detail
    if (
        words.length >= 15
    ) {
        score += 1;
    }

    if (
        words.length >= 30
    ) {
        score += 1;
    }

    if (
        words.length >= 50
    ) {
        score += 1;
    }


    // SPECIFIC DETAILS
    if (
        hasSpecificConcept
    ) {
        score += 1;
    }

    if (
        hasRole
    ) {
        score += 1;
    }

    if (
        hasMotivation
    ) {
        score += 1;
    }


    // WEAKNESS + VISUAL = Real character thinking
    if (
        hasWeakness && hasVisualIdentity
    ) {
        score += 2;
    }
    else if (
        hasWeakness || hasVisualIdentity
    ) {
        score += 1;
    }


    // ORIGINALITY: Reward varied vocabulary
    if (
        uniqueRatio >= 0.80
    ) {
        score += 2;
    }
    else if (
        uniqueRatio >= 0.70
    ) {
        score += 1;
    }


    // STRUCTURE
    if (
        hasStructure
    ) {
        score += 1;
    }


    // HARSH PENALTIES for generic
    if (
        words.length < 12
    ) {
        score -= 3;
    }
    else if (
        words.length < 15
    ) {
        score -= 2;
    }


    if (
        text.length < 35
    ) {
        score -= 2;
    }


    // PENALTY: Transformation without substance
    if (
        hasDistinctiveHook &&
        !hasWeakness &&
        !hasVisualIdentity
    ) {
        score -= 1;
    }


    return {
        score: Math.max(
            0,
            Math.min(
                10,
                score
            )
        ),
        details: {
            wordCount: words.length,
            uniqueRatio,
            hasSpecificConcept,
            hasRole,
            hasMotivation,
            hasDistinctiveHook,
            hasWeakness,
            hasVisualIdentity,
            hasStructure
        }
    };

}


function calculateScore(
    answer
) {

    return analyzeAnswer(
        answer
    ).score;

}


function judgeAnswers(
    player,
    phair
) {

    const playerAnalysis =
        analyzeAnswer(player);

    const phairAnalysis =
        analyzeAnswer(phair);


    const playerScore =
        playerAnalysis.score;

    const phairScore =
        phairAnalysis.score;


    showResults(
        player,
        playerScore,
        phair,
        phairScore,
        playerAnalysis,
        phairAnalysis
    );

}


/* =====================================================
   RESULTS
===================================================== */

function showResults(
    player,
    playerScore,
    phair,
    phairScore,
    playerAnalysis = null,
    phairAnalysis = null
) {

    gameScreen.classList.add(
        "hidden"
    );

    resultsScreen.classList.remove(
        "hidden"
    );


    if (
        playerScore > phairScore
    ) {

        winner.textContent =
            "YOU WIN";

        playerWins++;

        currentWinStreak++;

        bestWinStreak =
            Math.max(
                bestWinStreak,
                currentWinStreak
            );

        bestReachedLevel =
            Math.max(
                bestReachedLevel,
                level + 1
            );

        saveBestLevel();

        lastResultOutcome = "win";


        verdictText.textContent =
            playerAnalysis &&
            playerAnalysis.details
                ? (
                    "Your concept felt more original and specific. " +
                    "It had a clearer role, stronger hooks, and more defined identity than Phair's answer."
                )
                : (
                    "Your concept felt more original and specific. " +
                    "You changed enough of the idea to make it feel distinct from the inspiration."
                );

    }

    else if (
        playerScore < phairScore
    ) {

        winner.textContent =
            "PHAIR WINS";

        phairWins++;

        currentWinStreak = 0;

        lastResultOutcome = "loss";


        verdictText.textContent =
            phairAnalysis &&
            phairAnalysis.details
                ? (
                    "Phair's answer had stronger detail and clearer identity. " +
                    "It felt more developed, more specific, and more distinct from the source material."
                )
                : (
                    "Phair's answer had stronger detail and clearer identity. " +
                    "It felt more developed and distinct this round."
                );

    }

    else {

        winner.textContent =
            "IT'S A TIE";

        ties++;

        currentWinStreak = 0;

        lastResultOutcome = "tie";


        verdictText.textContent =
            "Both creations landed on a similar level of originality and detail. " +
            "Neither one pushed far enough beyond the inspiration to win clearly.";

    }

    updateProgressStatus();


    results.innerHTML = `

        <div class="result-card player">

            <div class="result-top">

                <span class="result-name">
                    YOUR CREATION
                </span>

                <span class="result-score">
                    ${playerScore}/10
                </span>

            </div>

            <p>
                ${escapeHTML(player)}
            </p>

        </div>


        <div class="result-card phair">

            <div class="result-top">

                <span class="result-name">
                    PHAIR HUGHES
                </span>

                <span class="result-score">
                    ${phairScore}/10
                </span>

            </div>

            <p>
                ${escapeHTML(phair)}
            </p>

        </div>

    `;


    updateScoreboard();


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


