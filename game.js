const roundModifiers = [
    "No generic powers. Make it specific.",
    "Give the concept a strong visual identity.",
    "Your answer should have a clear goal and weakness.",
    "Make the idea feel distinct from the original, not just updated.",
    "Include a memorable hook, team structure, or setting detail.",
    "A stronger identity beats a longer description."
];

function getDifficultyConfig(levelNumber) {

    const difficultyIndex =
        Math.min(
            levelNumber,
            difficultySettings.length - 1
        );

    const difficulty =
        difficultySettings[difficultyIndex];

    const extraLevelPressure =
        Math.max(
            0,
            Math.floor(levelNumber / 2)
        );

    const extraRestrictions = [];

    if (
        levelNumber >= 1
    ) {
        extraRestrictions.push(
            "No generic copy-paste ideas."
        );
    }

    if (
        levelNumber >= 2
    ) {
        extraRestrictions.push(
            "Give it a real flaw or limit."
        );
    }

    if (
        levelNumber >= 3
    ) {
        extraRestrictions.push(
            "The concept must feel meaningfully different."
        );
    }

    if (
        levelNumber >= 4
    ) {
        extraRestrictions.push(
            "Include a memorable visual identity."
        );
    }

    if (
        levelNumber >= 5
    ) {
        extraRestrictions.push(
            "Phair is reading for weak originality."
        );
    }

    if (
        levelNumber >= 8
    ) {
        extraRestrictions.push(
            "Make the world and motive feel specific."
        );
    }

    const modifierText =
        extraRestrictions.length > 0
            ? extraRestrictions.join(" ")
            : roundModifiers[
                levelNumber % roundModifiers.length
            ];

    return {
        difficulty,
        timeLimit: Math.max(
            20,
            difficulty.timeLimit - extraLevelPressure * 2
        ),
        modifierText,
        promptBonus: `${difficulty.promptBonus} ${modifierText}`
    };

}


