function startTimer(customTime = 60) {

    stopTimer();

    timeLeft = customTime;

    updateTimer();

    resumeTimer();
}


function resumeTimer() {

    if (
        timerInterval !== null ||
        roundSubmitted ||
        timeLeft <= 0
    ) {
        return;
    }


    timerInterval = setInterval(
        () => {

            if (roundSubmitted) {
                stopTimer();
                return;
            }

            timeLeft--;

            updateTimer();


            if (timeLeft <= 0) {

                timeOut();

            }

        },
        1000
    );
}


function pauseTimer() {

    if (
        timerInterval !== null
    ) {

        clearInterval(
            timerInterval
        );

        timerInterval = null;

    }
}


function stopTimer() {

    pauseTimer();

}


function updateTimer() {

    timerNumber.textContent =
        timeLeft;


    timer.classList.remove(
        "warning",
        "danger"
    );


    if (
        timeLeft <= 5
    ) {

        timer.classList.add(
            "danger"
        );

    }

    else if (
        timeLeft <= 15
    ) {

        timer.classList.add(
            "warning"
        );

    }

}


